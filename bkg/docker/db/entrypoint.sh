#!/bin/sh
# bkg-supafleet: entrypoint wrapper for PostgreSQL 18
#
# The official postgres:18 image keeps its cluster in $PGDATA
# (/var/lib/postgresql/18/docker) and declares VOLUME /var/lib/postgresql.
# The data volume therefore has to be mounted at /var/lib/postgresql.
# This wrapper must never relocate the cluster: a cluster outside the mounted
# volume would live in the container's writable layer and be lost on every
# `docker compose up --force-recreate`.
#
# The wrapper only adds what the base image does not provide:
#   1. a self-signed TLS certificate (Epistle and other clients require TLS)
#   2. passwords for the Supabase-compatible service roles, taken from
#      POSTGRES_PASSWORD so tenant containers can authenticate

set -e

CERT_DIR="/etc/postgresql/ssl"
CERT_FILE="$CERT_DIR/server.crt"
KEY_FILE="$CERT_DIR/server.key"
INIT_DIR="/docker-entrypoint-initdb.d"
PW_SQL="$INIT_DIR/02-role-passwords.sql"

# Roles that tenant containers authenticate as. They need LOGIN + a password.
SERVICE_ROLES="supabase_admin supabase_auth_admin supabase_storage_admin supabase_functions_admin authenticator"

case "$1" in
  postgres*)
    # ── 1. TLS certificate ────────────────────────────────────────────────
    if [ ! -s "$CERT_FILE" ] || [ ! -s "$KEY_FILE" ]; then
      echo "bkg-supafleet: generating self-signed TLS certificate"
      mkdir -p "$CERT_DIR"
      chmod 700 "$CERT_DIR"
      openssl req -x509 -newkey rsa:4096 -sha256 -nodes \
        -keyout "$KEY_FILE" \
        -out "$CERT_FILE" \
        -days 3650 \
        -subj "/CN=postgres.bkg-supafleet.local" \
        -addext "subjectAltName=DNS:postgres.bkg-supafleet.local,DNS:localhost,IP:127.0.0.1,IP:0:0:0:0:0:0:0:1" \
        2>/dev/null
      chmod 600 "$KEY_FILE"
      chmod 644 "$CERT_FILE"
      chown -R postgres:postgres "$CERT_DIR" 2>/dev/null || chown -R 999:999 "$CERT_DIR"
    fi

    # ── 2. Service role passwords ─────────────────────────────────────────
    # Only used on first init (the entrypoint runs /docker-entrypoint-initdb.d
    # scripts exactly once, when the cluster is created).
    if [ -n "${POSTGRES_PASSWORD:-}" ] && [ -d "$INIT_DIR" ] && [ -w "$INIT_DIR" ]; then
      if [ ! -f "$PW_SQL" ]; then
        # Strip newlines (they cannot survive a connection URL anyway) and
        # double single quotes so the value is a safe SQL string literal.
        esc=$(printf '%s' "$POSTGRES_PASSWORD" | tr -d '\n\r' | sed "s/'/''/g")
        {
          printf '%s\n' '-- generated by the bkg-supafleet entrypoint wrapper'
          for role in $SERVICE_ROLES; do
            printf 'ALTER ROLE "%s" WITH LOGIN PASSWORD %s;\n' "$role" "'$esc'"
          done
        } > "$PW_SQL"
        # The init scripts are executed as the `postgres` user — the file has
        # to be readable by that user, but nobody else.
        chown postgres:postgres "$PW_SQL" 2>/dev/null || chown 999:999 "$PW_SQL" || true
        chmod 600 "$PW_SQL"
      fi
    fi
    ;;
esac

# Run the original postgres entrypoint
exec /usr/local/bin/docker-entrypoint.sh "$@"
